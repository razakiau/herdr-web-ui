#!/usr/bin/env bun
/**
 * Generate the file icon tables from material-icon-theme (the icons VS Code's Material Icon Theme
 * draws), so a list names a file the way VS Code's explorer does.
 *
 *   bun run scripts/generate-file-icons.ts            # write the generated outputs
 *   bun run scripts/generate-file-icons.ts --check    # fail if a committed output is stale; never writes
 *
 * Outputs:
 *
 * - src/lib/fileIcons.generated.ts: the theme's file name and extension tables (dark and light),
 *   lowercased, as icon keys. Data only, so lib/fileIcons.ts and its tests read it under bun test.
 * - src/lib/fileIconUrls.generated.ts: one `?url&no-inline` import per icon the tables name, plus
 *   the fallbacks, so Vite emits each SVG as its own hashed /assets/ file the page fetches when a
 *   row shows it. Inlining them would put about half a megabyte of SVG into the main bundle.
 *
 * Folder names are left out: 4,659 names and 269 more icons for the folder browser alone, which
 * draws every folder as `folder` (and `.git` as `folder-git`).
 */

import { readFileSync, writeFileSync } from "node:fs";
import { basename, join, resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "..");
const PACKAGE = join(ROOT, "node_modules/material-icon-theme");
export const OUTPUTS = { tables: "src/lib/fileIcons.generated.ts", urls: "src/lib/fileIconUrls.generated.ts" } as const;

/** Icons lib/fileIcons.ts falls back to by name, beside the ones the tables name. */
export const FALLBACK_ICONS = [
  "file", "folder", "folder-open", "folder-git", "folder-git-open", "settings", "document", "image", "video", "audio", "zip", "console",
  "lock", "diff", "font", "key", "exe", "table", "json", "docker", "tune",
] as const;

interface Manifest {
  iconDefinitions: Record<string, { iconPath: string }>;
  fileNames: Record<string, string>;
  fileExtensions: Record<string, string>;
  light: { fileNames: Record<string, string>; fileExtensions: Record<string, string> };
}

/**
 * A table with its keys lowercased, as VS Code matches them. Where two keys differ only in case
 * (`CLAUDE.md` and `claude.md`), the lowercase one's icon wins.
 */
export function lowered(table: Record<string, string>): Record<string, string> {
  const out: Record<string, string> = {};
  for (const [key, icon] of Object.entries(table)) {
    const lower = key.toLowerCase();
    if (out[lower] === undefined || key === lower) out[lower] = icon;
  }
  return Object.fromEntries(Object.entries(out).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

export function render(manifest: Manifest, version: string): { tables: string; urls: string } {
  const tables = {
    FILE_NAMES: lowered(manifest.fileNames),
    FILE_EXTENSIONS: lowered(manifest.fileExtensions),
    LIGHT_FILE_NAMES: lowered(manifest.light.fileNames),
    LIGHT_FILE_EXTENSIONS: lowered(manifest.light.fileExtensions),
  };
  const used = new Set<string>(FALLBACK_ICONS);
  for (const table of Object.values(tables)) for (const icon of Object.values(table)) used.add(icon);
  const icons = [...used].sort();
  for (const icon of icons) if (manifest.iconDefinitions[icon] === undefined) throw new Error(`material-icon-theme names an icon it does not define: ${icon}`);
  const header = `// Generated by scripts/generate-file-icons.ts from material-icon-theme ${version} (MIT, THIRD_PARTY_NOTICES.md). Do not edit.\n`;
  const tableSource = header + Object.entries(tables)
    .map(([name, table]) => `export const ${name}: Readonly<Record<string, string>> = ${JSON.stringify(table)};\n`).join("");
  const urlSource = header
    + icons.map((icon, index) => `import i${index} from "material-icon-theme/icons/${basename(manifest.iconDefinitions[icon]!.iconPath)}?url&no-inline";\n`).join("")
    + `\nexport const ICON_URLS: Readonly<Record<string, string>> = {\n${icons.map((icon, index) => `  ${JSON.stringify(icon)}: i${index},\n`).join("")}};\n`;
  return { tables: tableSource, urls: urlSource };
}

if (import.meta.main) {
  const manifest = JSON.parse(readFileSync(join(PACKAGE, "dist/material-icons.json"), "utf8")) as Manifest;
  const { version } = JSON.parse(readFileSync(join(PACKAGE, "package.json"), "utf8")) as { version: string };
  const out = render(manifest, version);
  const check = process.argv.includes("--check");
  let stale = 0;
  for (const [key, path] of Object.entries(OUTPUTS) as [keyof typeof OUTPUTS, string][]) {
    const target = join(ROOT, path);
    let current = "";
    try { current = readFileSync(target, "utf8"); } catch { /* missing counts as stale */ }
    if (current === out[key]) continue;
    if (check) { console.error(`${path} is stale: run bun run generate:file-icons`); stale++; } else writeFileSync(target, out[key]);
  }
  process.exit(stale === 0 ? 0 : 1);
}
